/**
 * Generates supabase/seed.sql from the TypeScript seed data, so the bundled
 * demo catalogue and the database catalogue never drift apart.
 *
 *   npm run db:seed:generate
 *
 * Runs on Node 22.18+ with native TypeScript type stripping.
 */
import { writeFileSync } from "node:fs";
import { CATEGORY_LABELS } from "../src/lib/constants.ts";
import { HYDRATED_RECIPES } from "../src/data/seed/hydrate.ts";
import { INGREDIENTS } from "../src/data/seed/ingredients.ts";

const q = (v: string | null | undefined) => (v === null || v === undefined ? "null" : `'${v.replace(/'/g, "''")}'`);
const n = (v: number | null) => (v === null ? "null" : String(v));
const b = (v: boolean) => (v ? "true" : "false");
const arr = (v: string[]) => `array[${v.map(q).join(", ")}]::text[]`;

const out: string[] = [
  "-- Generated by scripts/generate-seed-sql.ts. Do not edit by hand.",
  "-- Ratings and review counts are SAMPLE values for the demo, not real reviews.",
  "begin;",
  "",
  "truncate public.recipe_substitutions, public.recipe_tips, public.recipe_steps, public.recipe_ingredients,",
  "  public.recipe_categories, public.recipes, public.categories, public.ingredients restart identity cascade;",
  "",
];

out.push(
  "insert into public.ingredients (id, name, plural, category, is_staple, contains_meat, contains_fish, contains_dairy, contains_egg, contains_honey, contains_gluten) values",
);
out.push(
  INGREDIENTS.map((i) => {
    const m = new Set(i.markers ?? []);
    return `  (${q(i.id)}, ${q(i.name)}, ${q(i.plural)}, ${q(i.category)}, ${b(!!i.staple)}, ${b(m.has("meat"))}, ${b(m.has("fish"))}, ${b(m.has("dairy"))}, ${b(m.has("egg"))}, ${b(m.has("honey"))}, ${b(m.has("gluten"))})`;
  }).join(",\n") + ";",
  "",
);

out.push("insert into public.categories (slug, name) values");
out.push(
  Object.entries(CATEGORY_LABELS)
    .map(([slug, name]) => `  (${q(slug)}, ${q(name)})`)
    .join(",\n") + ";",
  "",
);

for (const r of HYDRATED_RECIPES) {
  const d = new Set(r.diets);
  out.push(`-- ${r.title}`);
  out.push(
    `insert into public.recipes (slug, title, description, image_url, image_alt, prep_time, cook_time, rest_time, difficulty, cuisine, servings, rating, review_count, popularity, is_featured, is_vegetarian, is_vegan, is_gluten_free, is_dairy_free, calories, protein, carbohydrates, fat, nutrition_verified, notes, tags, created_at) values (` +
      [
        q(r.slug),
        q(r.title),
        q(r.description),
        q(r.imageUrl),
        q(r.imageAlt),
        n(r.prepTime),
        n(r.cookTime),
        n(r.restTime),
        q(r.difficulty),
        q(r.cuisine),
        n(r.servings),
        n(r.rating),
        n(r.reviewCount),
        n(r.popularity),
        b(r.featured),
        b(d.has("vegetarian")),
        b(d.has("vegan")),
        b(d.has("gluten-free")),
        b(d.has("dairy-free")),
        n(r.nutrition.calories),
        n(r.nutrition.protein),
        n(r.nutrition.carbohydrates),
        n(r.nutrition.fat),
        b(r.nutrition.verified),
        q(r.notes),
        arr(r.tags),
        q(`${r.createdAt}T09:00:00Z`),
      ].join(", ") +
      ");",
  );
  const rid = `(select id from public.recipes where slug = ${q(r.slug)})`;
  out.push(
    `insert into public.recipe_categories (recipe_id, category_id) select ${rid}, id from public.categories where slug in (${r.categories.map(q).join(", ")});`,
  );
  out.push(
    "insert into public.recipe_ingredients (recipe_id, ingredient_id, position, quantity, unit, note, is_optional) values",
  );
  out.push(
    r.ingredients
      .map(
        (i, idx) =>
          `  (${rid}, ${q(i.ingredientId)}, ${idx + 1}, ${n(i.quantity)}, ${q(i.unit)}, ${q(i.note)}, ${b(i.optional)})`,
      )
      .join(",\n") + ";",
  );
  out.push("insert into public.recipe_steps (recipe_id, step_number, instruction) values");
  out.push(r.steps.map((s, idx) => `  (${rid}, ${idx + 1}, ${q(s)})`).join(",\n") + ";");
  if (r.tips.length) {
    out.push("insert into public.recipe_tips (recipe_id, position, tip) values");
    out.push(r.tips.map((t, idx) => `  (${rid}, ${idx + 1}, ${q(t)})`).join(",\n") + ";");
  }
  if (r.substitutions.length) {
    out.push("insert into public.recipe_substitutions (recipe_id, position, ingredient, substitute) values");
    out.push(
      r.substitutions.map((s, idx) => `  (${rid}, ${idx + 1}, ${q(s.ingredient)}, ${q(s.substitute)})`).join(",\n") +
        ";",
    );
  }
  out.push("");
}

out.push("commit;", "");
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n"));
console.log(`Wrote supabase/seed.sql: ${INGREDIENTS.length} ingredients, ${HYDRATED_RECIPES.length} recipes.`);
